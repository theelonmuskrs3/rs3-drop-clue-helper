# Every line below is taken from the RS3 wiki page named in 'wiki' (wikitext snapshot of 21 Oct 2026). Nothing is invented.
# Only things the wiki describes as doable in the game today are in SECRETS; things the wiki marks gone are in PAST (collapsed, separate group).
#
# Entry keys: id, t (title), wiki (page), pic (wiki file candidates, first that exists is used), d (short description),
#   req [..], rw [{k: item|title|cosmetic|pet|emote, n: name, pic?: wiki file, item?: item name in the items list}],
#   steps [..], list {h: [col1, col2], rows: [[a, b], ..]}, maps [{l: label, map, plane, pins: [[x, y], ..]}], q (quick) , note

def M(l, x, y, map_=28, plane=0, *more):
    return {'l': l, 'map': '28' if str(map_) == '-1' else str(map_), 'plane': plane, 'pins': [[x, y]] + [list(m) for m in more]}

